// Resolves legacy lucide kebab names to lucide-vue-next 1.x exports and emits
// resources/src/config/menuIcons.js.
// Usage (from the project root, after npm install): node resources/scripts/gen-icons.cjs [icon-names.json] [lucide.d.ts] [out]
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const namesPath = process.argv[2] || path.join(ROOT, 'src/config/icon-names.json');
const dtsPath = process.argv[3] || path.join(ROOT, 'node_modules/lucide-vue-next/dist/lucide-vue-next.d.ts');
const outPath = process.argv[4] || path.join(ROOT, 'src/config/menuIcons.js');
const names = JSON.parse(fs.readFileSync(namesPath, 'utf8'));
const dts = fs.readFileSync(dtsPath, 'utf8');
const declared = new Set([...dts.matchAll(/declare const ([A-Za-z0-9_]+): vue\.FunctionalComponent/g)].map(m => m[1]));

const pascal = words => words.map(w => w.charAt(0).toUpperCase() + w.slice(1)).join('');

// Manual overrides for renames the heuristics can't derive.
const MANUAL = {
    'bar-chart': 'ChartBar',
    'bar-chart-3': 'ChartColumn',
    'pie-chart': 'ChartPie',
    'alarm-clock': 'AlarmClock',
};

function resolve(kebab) {
    if (MANUAL[kebab] && declared.has(MANUAL[kebab])) return MANUAL[kebab];
    const words = kebab.split('-');
    const candidates = [];
    candidates.push(pascal(words));
    // lucide 0.4xx Ã¢â€ â€™ 1.0 renames put the shape first: arrow-up-circle Ã¢â€ â€™ circle-arrow-up,
    // check-square Ã¢â€ â€™ square-check, layout-grid stays. Try every rotation.
    for (let i = 1; i < words.length; i++) candidates.push(pascal([...words.slice(i), ...words.slice(0, i)]));
    // numeric suffix dropped: bar-chart-3 Ã¢â€ â€™ ChartBar
    if (/^\d+$/.test(words[words.length - 1])) {
        const w = words.slice(0, -1);
        candidates.push(pascal(w));
        for (let i = 1; i < w.length; i++) candidates.push(pascal([...w.slice(i), ...w.slice(0, i)]));
    }
    return candidates.find(c => declared.has(c)) || null;
}

const map = {};
const unresolved = [];
for (const n of names) {
    const r = resolve(n);
    if (r) map[n] = r; else unresolved.push(n);
}
if (unresolved.length) {
    console.error('UNRESOLVED:', unresolved.join(' '));
}
const imports = [...new Set(Object.values(map))].sort();
const out = `/**
 * Sidebar icons Ã¢â‚¬â€ GENERATED by the gen-icons.js scratch script from the icon
 * names the legacy SaaS sidebar uses (config/menu.js \`icon\` values), resolved
 * against lucide-vue-next 1.x exports (several icons were renamed since the
 * legacy lucide-vue 0.5: bar-chart Ã¢â€ â€™ ChartBar, arrow-up-circle Ã¢â€ â€™ CircleArrowUp).
 *
 * Imported by name (not \`import *\`) to keep tree-shaking: lucide ships ~1,700
 * icons and the menu needs ${imports.length}.
 */
import {
    ${imports.join(', ')},
} from 'lucide-vue-next';

/** legacy kebab name -> lucide component */
export const MENU_ICONS = {
${Object.keys(map).sort().map(k => `    '${k}': ${map[k]},`).join('\n')}
};
`;
fs.writeFileSync(outPath, out);
console.log(`resolved ${Object.keys(map).length}/${names.length} icons, ${imports.length} unique components`);
