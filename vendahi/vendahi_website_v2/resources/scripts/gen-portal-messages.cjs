#!/usr/bin/env node
/**
 * Generates src/portal/messages.js from the stocky reference's
 * resources/lang/{en,fr,es,ar}/portal.php.
 *
 * Why bundled: this SaaS backend has no `portal.php` language files and no
 * GET /api/portal/translations/{locale} / POST /api/portal/locale endpoints
 * (stocky added them with its Vue 3 portal), and the backend/routes are
 * off-limits for this migration. The Vue 3 portal views are translated with
 * $t('key'), so the messages ship inside the bundle instead; the locale is
 * remembered per browser (localStorage) Ã¢â‚¬â€ see src/portal/i18n.js.
 *
 *   node resources/scripts/gen-portal-messages.cjs [path-to-stocky]
 *
 * The PHP files are flat `'key' => 'value',` arrays (no nesting) Ã¢â‚¬â€ parsed
 * with a regex, no PHP needed. Re-run after pulling a newer stocky.
 */
const fs = require('fs');
const path = require('path');

const STOCKY = process.argv[2] || 'D:/laragon/www/stocky';
const LOCALES = ['en', 'fr', 'es', 'ar'];
const OUT = path.resolve(__dirname, '..', '..', 'resources', 'src', 'portal', 'messages.js');

// 'key' => 'value',   |   "key" => "value",   (value may contain escaped quotes)
const LINE = /^\s*(['"])((?:\\.|(?!\1).)*)\1\s*=>\s*(['"])((?:\\.|(?!\3).)*)\3\s*,?\s*$/;

function parsePhp(file) {
    const out = {};
    for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
        const m = line.match(LINE);
        if (!m) continue;
        const unq = (v, q) => v.replace(new RegExp('\\\\' + q, 'g'), q).replace(/\\\\/g, '\\');
        out[unq(m[2], m[1])] = unq(m[4], m[3]);
    }
    return out;
}

const messages = {};
for (const loc of LOCALES) {
    const file = path.join(STOCKY, 'resources', 'lang', loc, 'portal.php');
    if (!fs.existsSync(file)) { console.error('missing', file); process.exit(1); }
    messages[loc] = parsePhp(file);
    console.log(`${loc}: ${Object.keys(messages[loc]).length} keys`);
}
const missing = Object.keys(messages.en).filter(k => LOCALES.some(l => !(k in messages[l])));
if (missing.length) console.log(`keys absent in some locale (fall back to en): ${missing.length}`);

const body = `// GENERATED by resources/scripts/gen-portal-messages.cjs from the stocky reference's
// resources/lang/{locale}/portal.php Ã¢â‚¬â€ do not edit by hand, re-run the script.
// Bundled because this backend has no portal translations endpoint.
/* eslint-disable */
export default ${JSON.stringify(messages, null, 2)};
`;
fs.writeFileSync(OUT, body);
console.log('wrote', path.relative(process.cwd(), OUT));
