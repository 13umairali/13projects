/** Where a legacy sidebar path should actually go. The legacy SaaS router is
 *  in history mode, so a legacy target is the bare '/app/...' path. */
export function resolveTarget(to) {
    if (!to) return null;
    const next = resolveMigratedPath(to);
    return next ? { type: 'next', path: next } : { type: 'legacy', path: to };
}
