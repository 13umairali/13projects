    public function run(): void
    {
        foreach ($this->superAdminPermissionList as $permission) {
            Permission::updateOrCreate(['name' => $permission,  'guard_name' => 'web']);
        }

        // Create roles with guard names
        $superAdminRole = Role::updateOrCreate(['name' => 'Admin', 'description' => 'This is Admin role', 'guard_name' => 'web']);

        /* Assign Permissions to Roles */
        $superAdminRole->syncPermissions($this->superAdminPermissionList);

        /** Now Create User */
        $this->createUser($superAdminRole, 'Admin', 'superadmin@gmail.com', '000000000001', '12345678', 'Admin', 1, 1);
    }

    public function createUser(Role $role, string $name, string $email, string $phone, string $password, $type, $instituteId = null, $branchId = null)
    {
        $user = User::factory([
            'name' => $name,
            'email' => $email,
            'password' => Hash::make($password),
            'phone' => $phone,
            'user_type' => $type,
            'role_id' => $role->id,
            'remember_token' => Str::random(10),
            'platform' => 'WEB',
            'email_verified_at' => Carbon::now(),
            'last_active_time' => Carbon::now(),
            'status' => 1,
            'user_status' => 1,
        ])->create();

        /* Get all the permission and assign admin role */
        $user->assignRole([$role->id]);
    }
